NATIVE = ["", "한", "두", "세", "네", "다섯", "여섯", "일곱", "여덟", "아홉", "열", "열한", "열두"]


def sino(n):
    s = ""
    if n >= 100:
        s += ("" if n // 100 == 1 else DIG[n // 100]) + "백"
        n %= 100
    if n >= 10:
        s += ("" if n // 10 == 1 else DIG[n // 10]) + "십"
        n %= 10
    return s + (DIG[n] if n else "")


def M(spoken, written):
    return f"⟦{spoken}|{written}⟧"


def temp(n): return M(f"{sino(n)} 도", f"{n}도")
def pct(n): return M(f"{sino(n)} 퍼센트", f"{n}퍼센트")
def minutes(n): return M(f"{sino(n)} 분", f"{n}분")
def hours(n): return M(f"{NATIVE[n]} 시간", f"{n}시간")
def clock(n): return M(f"{NATIVE[n]} 시", f"{n}시")
def level(n): return M(f"{sino(n)} 단계", f"{n}단계")


def jong(w):
    c = w.rstrip()[-1]
    return "가" <= c <= "힣" and (ord(c) - 0xAC00) % 28 != 0


def j(w, pair):  # 조사: j("불", "을/를") → "불을"
    a, b = pair.split("/")
    return w + (a if jong(w) else b)


def render(s):
    """⟦a|b⟧ → (읽는 말, 숫자 표기, 숫자 키워드 목록)"""
    nums = re.findall(r"⟦([^|]+)\|([^⟧]+)⟧", s)
    return (re.sub(r"⟦([^|]+)\|[^⟧]+⟧", r"\1", s), re.sub(r"⟦[^|]+\|([^⟧]+)⟧", r"\1", s),
            [f"{a}|{b}" for a, b in nums])


