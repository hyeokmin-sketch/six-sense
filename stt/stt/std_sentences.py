def fill(act, rnd):
    one = M("한 도", "1도") if rnd.random() < .5 else M("두 도", "2도")
    return act.format(pct=pct(rnd.choice(range(10, 101, 10))), temp=temp(rnd.randint(18, 30)),
                      hours=hours(rnd.randint(1, 4)), level=level(rnd.randint(1, 5)), one=one)


def command(dev_kind, rnd, loc=None, ending=None):
    locs, devs, acts = {"light": (LOCS_LIGHT, LIGHTS, LIGHT_ACT), "blind": (LOCS, BLINDS, BLIND_ACT),
                        "ac": (LOCS, ACS, AC_ACT)}[dev_kind]
    loc = rnd.choice(locs + [""] * 4) if loc is None else loc
    dev = rnd.choice(devs)
    act, akw, obj = rnd.choice(acts)
    noun = (loc + " " if loc else "") + dev
    if obj and rnd.random() < .3:
        noun = j(noun, "을/를")
    jom = "좀 " if "좀" not in act and rnd.random() < .2 else ""
    end = rnd.choice(ENDINGS) if ending is None else ending
    return f"{noun} {jom}{fill(act, rnd)}{end}", {"device": [DEV_KW[dev_kind]], "action": [akw]}


