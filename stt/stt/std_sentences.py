def general(rnd):
    out = [("일상", s.strip(), {}) for s in DAILY if s.strip()]
    out += [("질문", s.strip(), {}) for s in QUESTIONS_G if s.strip()]
    out += [("감정", s.strip(), {}) for s in EMOTION if s.strip()]
    for _ in range(4000):
        g, f = rnd.choice(GEN_TEMPLATES)
        out.append((g, re.sub(r"\s+", " ", f(rnd)).strip(), {}))
    return out


def pick(cands, n, rnd, prefix, setname, keep_all=()):
    """중복(읽는 말 기준) 제거 후 n개. keep_all 그룹은 전부, 나머지는 그룹 비율대로 무작위"""
    seen, uniq = set(), []
    for g, s, kw in cands:
        sp = render(s)[0]
        if sp not in seen:
            seen.add(sp)
            uniq.append((g, s, kw))
    keep = [x for x in uniq if x[0] in keep_all]
    rest = [x for x in uniq if x[0] not in keep_all]
    rnd.shuffle(rest)
    chosen = keep + rest[:n - len(keep)]
    rnd.shuffle(chosen)
    recs = []
    for i, (g, s, kw) in enumerate(chosen, 1):
        sp, wr, nums = render(s)
        kw = dict(kw)
        if nums:
            kw["number"] = nums
        recs.append({"id": f"{prefix}{i:04d}", "set": setname, "group": g, "text": sp,
                     **({"alt": wr} if wr != sp else {}), "keywords": kw})
    return recs


def main():
    rnd = random.Random(SEED)
    gen = pick(general(rnd), N_GENERAL, rnd, "G", "general", keep_all=("일상", "질문", "감정"))
    dom = pick(domain(rnd), N_DOMAIN, rnd, "D", "domain", keep_all=("상황", "질문"))
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "sentences.jsonl"), "w", encoding="utf-8") as f:
        for r in gen + dom:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    for name, recs in (("general", gen), ("domain", dom)):
        cnt = {}
        for r in recs:
            cnt[r["group"]] = cnt.get(r["group"], 0) + 1
        print(name, len(recs), dict(sorted(cnt.items(), key=lambda x: -x[1])))


if __name__ == "__main__":
    main()
