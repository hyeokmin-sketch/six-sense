def domain(rnd):
    out = []  # (group, 문장, keywords)
    dev_of = {"light": LIGHTS, "blind": BLINDS, "ac": ACS}
    for kind, n in (("light", 750), ("blind", 650), ("ac", 750)):
        for _ in range(n * 3):
            s, kw = command(kind, rnd)
            out.append((f"명령_{kind}", s, kw))
    for kind, rs in REASONS.items():
        for _ in range(350):
            reason, acts = rnd.choice(rs)
            loc = rnd.choice(LOCS + [""] * 3)
            dev = rnd.choice(dev_of[kind])
            act = rnd.choice(acts)
            noun = (loc + " " if loc else "") + dev
            out.append(("상황+명령", f"{reason} {noun} {fill(act, rnd)}{rnd.choice(ENDINGS)}",
                        {"device": [DEV_KW[kind]], "action": [ACT_KW.get(act, act.split()[0])]}))
    for kind, t in STATEMENTS:
        for loc in rnd.sample(LOCS, 6) if "{loc}" in t else [""]:
            s = t.format(loc=j(loc, "이/가") if loc else "").strip()
            out.append(("상황", s, {"device": [DEV_KW[kind]] if kind in ("blind", "ac") and DEV_KW[kind] in s else [],
                                    "action": []}))
    for kind, t, akw in QUESTIONS:
        for _ in range(25):
            loc = rnd.choice(LOCS + [""])
            s = re.sub(r"\s+", " ", t.format(loc=loc, light=rnd.choice(LIGHTS))).strip()
            out.append(("질문", s, {"device": [DEV_KW[kind]], "action": [akw]}))
    kinds = list(GO)
    for _ in range(600):
        k1, k2 = rnd.sample(kinds, 2)
        c1, a1 = rnd.choice(GO[k1])
        noun1 = rnd.choice(["", rnd.choice(LOCS) + " "]) + rnd.choice(dev_of[k1])
        s2, kw2 = command(k2, rnd, loc="")
        out.append(("복합", f"{noun1} {c1} {s2}", {"device": [DEV_KW[k1]] + kw2["device"], "action": [a1] + kw2["action"]}))
    for s, kw in [("집에 있는 불 다 꺼 줘", ("light", "꺼")), ("모든 조명 다 켜 줘", ("light", "켜")),
                  ("에어컨이랑 불 다 꺼 줘", ("ac", "꺼")), ("블라인드 전부 다 내려 줘", ("blind", "내려")),
                  ("외출 모드로 다 꺼 줘", ("light", "꺼")), ("집에 있는 블라인드 다 올려 줘", ("blind", "올려"))]:
        out.append(("복합", s, {"device": [DEV_KW[kw[0]]], "action": [kw[1]]}))
    for _ in range(700):
        kind = rnd.choice(kinds)
        s, kw = command(kind, rnd)
        out.append(("예약", f"{rnd.choice(WHEN)(rnd)} {s}", kw))
    return out


